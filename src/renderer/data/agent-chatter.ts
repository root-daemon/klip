export function randomAgentLine(agentId: string): string {
  const bank = BANKS[agentId] ?? BANKS.conversation;
  const doing = bank.doing[Math.floor(Math.random() * bank.doing.length)];
  const reaction = bank.reaction[Math.floor(Math.random() * bank.reaction.length)];
  const template = TEMPLATES[Math.floor(Math.random() * TEMPLATES.length)];
  return template(doing, reaction);
}
